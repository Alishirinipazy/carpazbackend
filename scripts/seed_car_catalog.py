def main():
    db = SessionLocal()
    added_models = 0
    added_trims = 0
    skipped_brands: list[str] = []

    try:
        for brand_name, models in CATALOG.items():
            brand = db.query(Brand).filter(Brand.name == brand_name).first()
            if brand is None:
                skipped_brands.append(brand_name)
                continue

            for model_name, trims in models.items():
                model = db.query(CarModel).filter(
                    CarModel.brand_id == brand.id, CarModel.name == model_name
                ).first()
                if model is None:
                    model = CarModel(brand_id=brand.id, name=model_name, slug=slugify(f"{brand_name}-{model_name}"))
                    db.add(model)
                    db.flush()
                    added_models += 1

                for trim_name in trims:
                    exists = db.query(CarTrim).filter(
                        CarTrim.model_id == model.id, CarTrim.name == trim_name
                    ).first()
                    if exists is None:
                        db.add(CarTrim(model_id=model.id, name=trim_name))
                        added_trims += 1

        db.commit()
        print(f"Added {added_models} model(s) and {added_trims} trim(s).")
        if skipped_brands:
            print(f"Skipped (brand not found in DB - run seed_brands.py first): {', '.join(skipped_brands)}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
